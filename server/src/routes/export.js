import { Router } from 'express';
import PDFDocument from 'pdfkit';

const router = Router();

/** POST /api/export/pdf - render a summary to a downloadable PDF. */
router.post('/pdf', (req, res) => {
  const title = String(req.body.title || 'IsaacSum Summary').slice(0, 200);
  const content = String(req.body.content || '');

  if (!content.trim()) {
    return res.status(400).json({ error: 'Nothing to export.' });
  }

  const doc = new PDFDocument({ margin: 56, size: 'A4' });

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="${slugify(title) || 'summary'}.pdf"`
  );

  doc.pipe(res);

  // Header
  doc.fontSize(9).fillColor('#888888').text('IsaacSum', { continued: true });
  doc.fillColor('#000000');
  doc.moveDown(0.5);
  doc.fontSize(20).text(title);
  doc.moveDown(0.3);
  doc
    .moveTo(56, doc.y)
    .lineTo(doc.page.width - 56, doc.y)
    .strokeColor('#dddddd')
    .stroke();
  doc.moveDown(1);

  // Body: minimal markdown-ish handling.
  for (const rawLine of content.replace(/\r\n/g, '\n').split('\n')) {
    const line = rawLine.replace(/\*\*/g, '');
    if (!line.trim()) {
      doc.moveDown(0.6);
      continue;
    }
    if (/^#{1,6}\s/.test(line)) {
      doc.fontSize(14).fillColor('#1a1a2e').text(line.replace(/^#{1,6}\s/, ''));
      doc.fillColor('#000000');
    } else if (/^[-*•]\s/.test(line)) {
      doc
        .fontSize(11)
        .fillColor('#333333')
        .text(`• ${line.replace(/^[-*•]\s/, '')}`, { indent: 14 });
    } else {
      doc.fontSize(11).fillColor('#333333').text(line);
    }
  }

  // Footer
  doc.moveDown(2);
  doc
    .fontSize(8)
    .fillColor('#999999')
    .text(`Generated by IsaacSum · ${new Date().toLocaleString()}`);

  doc.end();
});

function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 50);
}

export default router;
